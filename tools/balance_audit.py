"""Level-curve audit: compares each map's levels with the gym leader the
player is heading toward (badges_expected + 1). Writes progress/BALANCE.md.

    python3 tools/balance_audit.py
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import DATABASE_DIR, REPO_DIR, read_csv  # noqa: E402

GYMS = ["roxanne-1", "brawly-1", "wattson-1", "flannery-1", "norman-1", "winona-1", "tate-and-liza-1", "juan-1"]


def main() -> None:
    parties = defaultdict(list)
    for p in read_csv(DATABASE_DIR / "trainer_parties.csv"):
        if p["level"].isdigit():
            parties[p["trainer_id"]].append(int(p["level"]))
    ace = {i: max(parties["trainer:" + g]) for i, g in enumerate(GYMS)}
    ace[8] = max(parties["trainer:wallace"])
    rows = read_csv(DATABASE_DIR / "area_progression.csv")
    by_tier = defaultdict(list)
    for r in rows:
        if r["badges_expected"] != "":
            by_tier[int(r["badges_expected"])].append(r)
    out = ["# Balance audit", "", "Generated by `python3 tools/balance_audit.py`.", "",
           "Next boss = the Gym Leader the player is working toward with that many badges (8 = Champion Wallace).",
           "A map is flagged when its first-tier trainers or land encounters exceed the next boss's ace level, "
           "or sit more than 15 levels below the previous boss (likely mis-tiered).", "",
           "| Badges | Next boss | Boss ace Lv | Maps | Wild land range | Trainer range | Flags |", "|---:|---|---:|---:|---|---|---|"]
    flags_detail = []
    for tier in sorted(by_tier):
        maps = by_tier[tier]
        nxt = ace.get(tier, ace[8])
        prev = ace.get(tier - 1, 5)
        wl = [int(r["wild_land_max"]) for r in maps if r["wild_land_max"]]
        tl = [int(r["trainer_level_max"]) for r in maps if r["trainer_level_max"]]
        n = 0
        for r in maps:
            hi = max([int(x) for x in (r["trainer_level_max"], r["wild_land_max"]) if x] or [0])
            if hi and (hi > nxt or (tier and hi < prev - 15)):
                n += 1
                flags_detail.append(f"- `{r['map_id']}` badges={tier}: max Lv {hi} vs next boss {nxt} / previous boss {prev} — {r.get('gating_notes', '')}")
        boss = GYMS[tier] if tier < 8 else "wallace"
        out.append(f"| {tier} | {boss} | {nxt} | {len(maps)} | {min(wl, default='')}–{max(wl, default='')} | {min(tl, default='')}–{max(tl, default='')} | {n} |")
    out += ["", "## Flagged maps", ""] + (flags_detail or ["(none)"])
    (REPO_DIR / "progress" / "BALANCE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
